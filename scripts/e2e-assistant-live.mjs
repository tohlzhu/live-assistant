import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify, parseArgs } from "node:util";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { randomUUID } from "node:crypto";
import { chromium } from "@playwright/test";
import { startAssistant } from "../packages/live-assistant/src/server.mjs";
import { FoundryLive } from "../packages/live-assistant/src/live.mjs";
import { JsonStore } from "../packages/live-assistant/src/store.mjs";

const run = promisify(execFile);
const { values } = parseArgs({ options: { mandarin: { type: "boolean" }, "mandarin-fixtures": { type: "string" } } });
const directory = resolve(".live-assistant", `voice-acceptance-${new Date().toISOString().replaceAll(":", "-")}`);
await mkdir(directory, { recursive: true, mode: 0o700 });
let audioFile = join(directory, "caller.wav");
const mandarin = values.mandarin === true;
if (values["mandarin-fixtures"] && !mandarin) throw new Error("Mandarin fixtures require --mandarin");
await run("espeak-ng", ["-v", "en-us", "-s", "140", "-w", audioFile, "Hello. Please create a new shell session for local testing. Do not execute any commands."]);
const liveEndpoint = process.env.FOUNDRY_LIVE_ENDPOINT;
const intentEndpoint = process.env.FOUNDRY_INTENT_ENDPOINT;
if (!liveEndpoint || !intentEndpoint) throw new Error("Set FOUNDRY_LIVE_ENDPOINT and FOUNDRY_INTENT_ENDPOINT to authorized Foundry HTTPS roots");
const subscription = process.env.AZURE_SUBSCRIPTION_NAME;
const deployment = process.env.FOUNDRY_LIVE_DEPLOYMENT ?? "gpt-live-1";
const password = randomUUID();
const app = await startAssistant({
  directory, workspace: join(directory, "workspace"), password,
  foundry: {
    liveEndpoint, intentEndpoint, ttsEndpoint: process.env.FOUNDRY_TTS_ENDPOINT, deployment, voice: process.env.FOUNDRY_LIVE_VOICE, subscription,
    intentDeployment: process.env.FOUNDRY_INTENT_DEPLOYMENT, intentEffort: process.env.FOUNDRY_INTENT_EFFORT,
  },
});
let browser;
const result = { passed: false, input: mandarin ? "synthetic Mandarin generated by GPT-Live; not human or physical-device acceptance" : "synthetic English; not physical-device or Mandarin acceptance" };
const virtualMicrophone = () => {
  const context = new AudioContext();
  window.acceptanceAudio = { context, mic: null };
  navigator.mediaDevices.getUserMedia = async () => {
    await context.resume();
    const mic = context.createMediaStreamDestination();
    window.acceptanceAudio.mic = mic;
    return mic.stream;
  };
};
async function renderMandarin(browser, phrase, name) {
  if (values["mandarin-fixtures"]) {
    const source = resolve(values["mandarin-fixtures"]);
    const evidence = JSON.parse(await readFile(join(source, "result.json"), "utf8"));
    assert.equal(evidence.passed, true, "Only previously accepted speech fixtures may be reused");
    const fixture = evidence.speechFixtures.find((entry) => entry.name === name);
    assert.equal(fixture.transcript.replace(/[\s。,.，!！?？]/g, ""), phrase.replace(/[\s。,.，!！?？]/g, ""));
    assert.equal(evidence.speechFixtureClosures.find((entry) => entry.name === name).closeConfirmed, true);
    const file = join(source, `${name}-mandarin.webm`);
    assert.equal((await readFile(file)).length, fixture.bytes);
    result.speechFixtures ??= [];
    result.speechFixtures.push({ ...fixture, reusedFrom: source });
    return file;
  }
  const speechDirectory = join(directory, `speech-fixture-${name}`);
  const record = new JsonStore(join(speechDirectory, "live.json"), null);
  const live = new FoundryLive({
    endpoint: liveEndpoint, deployment, subscription,
    instructions: `You are a Mandarin speech fixture renderer. On caller input, speak exactly this ONE sentence once in natural Mandarin, without any introduction, explanation or delegation: ${phrase} You never execute or authorize work.`,
  }, { load: () => record.value ?? undefined, save: async (value) => { record.value = structuredClone(value); record.save(); } });
  await live.initialize();
  const renderPassword = randomUUID();
  const renderer = await startAssistant({ directory: speechDirectory, workspace: join(speechDirectory, "workspace"), password: renderPassword, live });
  let page;
  try {
    const instruction = join(speechDirectory, "render.wav");
    await run("espeak-ng", ["-v", "en-us", "-s", "140", "-w", instruction, "Please read the sentence in your instructions aloud once, and nothing else."]);
    page = await browser.newPage();
    await page.addInitScript(virtualMicrophone);
    await page.route("**/render.wav", (route) => readFile(instruction).then((body) => route.fulfill({ body, contentType: "audio/wav" })));
    await page.goto(renderer.origin);
    await page.locator("#password").fill(renderPassword);
    await page.locator("#login button").click();
    await page.locator("#connect").click();
    await page.waitForFunction(() => document.querySelector("#live-status").dataset.state === "active" && document.getElementById("audio").srcObject, null, { timeout: 40000 });
    await page.evaluate(async () => {
      const recorder = new MediaRecorder(document.getElementById("audio").srcObject);
      const chunks = [];
      recorder.ondataavailable = (event) => chunks.push(event.data);
      window.speechRecording = { recorder, chunks };
      recorder.start();
      const { context, mic } = window.acceptanceAudio;
      const source = context.createBufferSource();
      source.buffer = await context.decodeAudioData(await (await fetch("/render.wav")).arrayBuffer());
      source.connect(mic); source.start();
    });
    const deadline = Date.now() + 40000;
    const normalized = (text) => text.replace(/[\s。,.，!！?？]/g, "");
    while (normalized(live.diagnostics().output) !== normalized(phrase) && Date.now() < deadline) await page.waitForTimeout(300);
    assert.equal(normalized(live.diagnostics().output), normalized(phrase));
    await page.waitForTimeout(3000);
    assert.equal(normalized(live.diagnostics().output), normalized(phrase));
    const recording = await page.evaluate(() => new Promise((done) => {
      const { recorder, chunks } = window.speechRecording;
      recorder.onstop = async () => done(Array.from(new Uint8Array(await new Blob(chunks, { type: recorder.mimeType }).arrayBuffer())));
      recorder.stop();
    }));
    assert.ok(recording.length > 1000);
    const file = join(directory, `${name}-mandarin.webm`);
    await writeFile(file, Buffer.from(recording), { mode: 0o600 });
    result.speechFixtures ??= [];
    result.speechFixtures.push({ name, transcript: live.diagnostics().output, bytes: recording.length, source: "GPT-Live synthesized Mandarin, not human speech" });
    assert.equal(renderer.sessions.list().length, 0);
    return file;
  } finally {
    await page?.close();
    await renderer.close();
    result.speechFixtureClosures ??= [];
    result.speechFixtureClosures.push({ name, closeConfirmed: live.diagnostics().closeConfirmed, seconds: live.diagnostics().seconds });
    assert.equal(live.diagnostics().closeConfirmed, true);
  }
}
try {
  // Without an override Playwright launches the Chromium it installed (`npx playwright install chromium`).
  const executablePath = process.env.LIVE_ASSISTANT_CHROMIUM || undefined;
  browser = await chromium.launch({ executablePath, headless: true, chromiumSandbox: true, args: ["--autoplay-policy=no-user-gesture-required"] });
  let statusFile;
  if (mandarin) {
    audioFile = await renderMandarin(browser, "请创建一个空的 shell 会话。", "create");
    statusFile = await renderMandarin(browser, "请查看所有会话的状态。", "status");
  }
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.addInitScript(virtualMicrophone);
  await page.route("**/acceptance.wav", async (route) => route.fulfill({ body: await readFile(audioFile), contentType: mandarin ? "audio/webm" : "audio/wav" }));
  if (statusFile) await page.route("**/status.webm", async (route) => route.fulfill({ body: await readFile(statusFile), contentType: "audio/webm" }));
  await page.goto(app.origin);
  await page.locator("#password").fill(password);
  await page.locator("#login button").click();
  await page.locator("#workspace").waitFor({ state: "visible" });
  await page.locator("#connect").click();
  await page.waitForFunction(() => document.querySelector("#live-status").dataset.state === "active" && document.getElementById("audio").srcObject, null, { timeout: 40000 });
  await page.evaluate(async () => {
    const { context, mic } = window.acceptanceAudio;
    const source = context.createBufferSource();
    source.buffer = await context.decodeAudioData(await (await fetch("/acceptance.wav")).arrayBuffer());
    source.connect(mic); source.start();
    const audio = document.getElementById("audio");
    const playback = context.createMediaStreamSource(audio.srcObject);
    const analyser = context.createAnalyser(); playback.connect(analyser);
    window.acceptanceMax = 0;
    window.acceptanceMeter = setInterval(() => {
      const data = new Float32Array(analyser.fftSize); analyser.getFloatTimeDomainData(data);
      window.acceptanceMax = Math.max(window.acceptanceMax, ...data.map(Math.abs));
    }, 50);
  });
  const deadline = Date.now() + 60000;
  const waiting = (kind, sessionId) => app.sessions.pending().find((row) => row.state === "pending" && row.kind === kind && (!sessionId || row.sessionId === sessionId));
  while (!waiting("create") && Date.now() < deadline) await page.waitForTimeout(500);
  const pending = waiting("create");
  assert.ok(pending, "Voice did not produce a grounded operation proposal");
  assert.equal(pending.harness, "shell");
  if (mandarin) assert.equal(pending.data, "", "An empty terminal request must not invent a command");
  assert.equal(app.sessions.list().length, 0, "Voice proposal must not execute before approval");
  await page.locator(`#decisions .decision:has(.number:text-is("${pending.number}.")) button:text-is("批准")`).click();
  await page.waitForFunction(() => document.querySelectorAll("#tabs .tab").length === 1);
  // The shell reads the user's ~/.bashrc, so wait for its prompt to render instead of matching a fixed prompt.
  await page.waitForFunction(() => document.querySelector("#terminal .xterm-rows")?.textContent.trim().length > 0);
  const session = app.sessions.list()[0];
  assert.equal(session.harness, "shell");
  await page.locator("#mute").click();
  assert.equal(app.sessions.get(session.id).state, "running");
  await page.locator("#mute").click();
  await page.waitForFunction(() => window.acceptanceMax > 0.001, null, { timeout: 15000 });
  result.playbackPeak = await page.evaluate(() => window.acceptanceMax);
  result.diagnostics = app.assistant.state().live;
  assert.ok(result.diagnostics.input.length > 0);
  assert.ok(result.diagnostics.output.length > 0);
  assert.deepEqual(errors, []);
  await page.locator("#connect.connected").click();
  await page.waitForFunction(() => document.querySelector("#live-status").dataset.state === "disconnected");
  assert.equal(app.sessions.get(session.id).state, "running");
  result.firstClosure = app.assistant.state().live;
  if (mandarin) {
    const background = await app.sessions.create({ harness: "shell", name: "background" }, randomUUID());
    const command = "sleep 20; printf '\\nProceed? [y/N]'; read -r answer; test \"$answer\" != y || printf confirmed > voice-confirmed.txt";
    await app.assistant.request(`在现有 shell 会话 ${background.id} 中追加执行下面这个明确的命令，不新建会话，完整保留命令：${command}`);
    const proposed = waiting("input", background.id);
    assert.ok(proposed);
    assert.equal(proposed.data, `${command}\r`);
    await app.sessions.decide(proposed.id, true, randomUUID());
    const pid = app.sessions.get(background.id).pid;
    const observations = [];
    app.assistant.on("status-observed", (event) => observations.push(event));
    await page.locator("#connect").click();
    await page.waitForFunction(() => document.querySelector("#live-status").dataset.state === "active" && document.getElementById("audio").srcObject, null, { timeout: 40000 });
    const beforeOutput = app.assistant.state().live.output;
    await page.evaluate(async () => {
      window.acceptanceMax = 0;
      const { context, mic } = window.acceptanceAudio;
      const source = context.createBufferSource();
      source.buffer = await context.decodeAudioData(await (await fetch("/status.webm")).arrayBuffer());
      source.connect(mic); source.start();
      const analyser = context.createAnalyser();
      context.createMediaStreamSource(document.getElementById("audio").srcObject).connect(analyser);
      clearInterval(window.acceptanceMeter);
      window.acceptanceMeter = setInterval(() => {
        const data = new Float32Array(analyser.fftSize); analyser.getFloatTimeDomainData(data);
        window.acceptanceMax = Math.max(window.acceptanceMax, ...data.map(Math.abs));
      }, 50);
    });
    const statusDeadline = Date.now() + 30000;
    while ((!observations.length || !/(会话|终端|运行|等待|确认|后台)/.test(app.assistant.state().live.output.slice(beforeOutput.length))) && Date.now() < statusDeadline) await page.waitForTimeout(300);
    assert.match(app.assistant.state().live.input, /状态/);
    assert.notEqual(app.assistant.state().live.output, beforeOutput);
    assert.ok(observations.some((event) => event.sessionIds.length === 2), "The real voice status query must observe both existing sessions");
    assert.match(app.assistant.state().live.output.slice(beforeOutput.length), /(会话|终端|运行|等待|确认|后台)/, "Spoken status must discuss actual terminal work, not just acknowledge the user");
    assert.equal(app.sessions.list().length, 2);
    assert.equal(app.sessions.pending().filter((row) => row.state === "pending").length, 0);
    assert.equal(app.sessions.get(background.id).pid, pid);
    result.statusDuringBackgroundWork = { input: app.assistant.state().live.input, output: app.assistant.state().live.output, sessions: 2, observations };
    await page.waitForFunction(() => window.acceptanceMax > 0.001, null, { timeout: 15000 });
    const promptDeadline = Date.now() + 30000;
    while (!waiting("prompt", background.id) && Date.now() < promptDeadline) await page.waitForTimeout(300);
    const prompt = waiting("prompt", background.id);
    assert.ok(prompt, "The native [y/N] prompt must become a numbered proposal");
    await assert.rejects(readFile(join(directory, "workspace", "shell-work", "voice-confirmed.txt")), { code: "ENOENT" });
    await page.locator(`#decisions .decision:has(.number:text-is("${prompt.number}.")) button:text-is("批准")`).click();
    const fileDeadline = Date.now() + 5000;
    let contents;
    while (Date.now() < fileDeadline) {
      try { contents = await readFile(join(directory, "workspace", "shell-work", "voice-confirmed.txt"), "utf8"); break; }
      catch (error) { if (error.code !== "ENOENT") throw error; }
      await page.waitForTimeout(100);
    }
    assert.equal(contents, "confirmed");
    await writeFile(join(directory, "workspace", "shell-work", "voice-verify.mjs"), 'import {readFileSync} from "node:fs";import assert from "node:assert/strict";assert.equal(readFileSync("voice-confirmed.txt","utf8"),"confirmed");\n');
    const verification = await app.sessions.startVerification(
      background.id, app.sessions.get(background.id).currentRunId,
      `${JSON.stringify(process.execPath)} voice-verify.mjs`, randomUUID(),
    );
    result.backgroundVerification = await verification.completion;
    assert.equal(result.backgroundVerification.state, "passed");
    assert.equal(result.backgroundVerification.exitCode, 0);
    await page.locator("#connect.connected").click();
    await page.waitForFunction(() => document.querySelector("#live-status").dataset.state === "disconnected");
    assert.equal(app.sessions.get(background.id).pid, pid);
    assert.equal(app.sessions.get(background.id).state, "running");
    result.reconnectPreservedNativeTask = true;
  }
  result.passed = true;
} catch (error) { result.error = error.message; process.exitCode = 1; }
finally {
  await browser?.close();
  for (const session of app.sessions.list()) if (["running", "exited"].includes(session.state)) await app.sessions.terminate(session.id, randomUUID());
  try { await app.close(); }
  catch (error) { result.closeError = error.message; result.passed = false; process.exitCode = 1; }
  result.finalLive = app.assistant.state().live;
  await writeFile(join(directory, "result.json"), JSON.stringify(result, null, 2), { mode: 0o600 });
  console.log(JSON.stringify({ passed: result.passed, error: result.error, closeError: result.closeError, artifact: join(directory, "result.json"), closeConfirmed: result.finalLive.closeConfirmed, seconds: result.finalLive.seconds }));
}
