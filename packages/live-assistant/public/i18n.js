const languages = Object.keys(messages);
// A saved choice wins; otherwise the browser's first Chinese or English preference, and English for any other language.
function preferredLanguage() {
  try { const saved = localStorage.getItem("live-lang"); if (languages.includes(saved)) return saved; } catch {}
  for (const tag of navigator.languages?.length ? navigator.languages : [navigator.language ?? ""]) {
    if (/^zh\b/i.test(tag)) return "zh-CN";
    if (/^en\b/i.test(tag)) return "en";
  }
  return "en";
}
let lang = preferredLanguage();
function t(key, values = {}, language = lang) {
  const message = messages[language]?.[key] ?? messages["zh-CN"][key] ?? key;
  if (typeof message === "function") return message(values);
  return message.replace(/\{(\w+)\}/g, (match, name) => name in values ? String(values[name]) : match);
}
// Static markup names its text by key: data-i18n for the content, data-i18n-<attribute> for title, aria-label and placeholder.
function translatePage() {
  document.documentElement.lang = lang;
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const attribute of ["title", "aria-label", "placeholder"]) {
    for (const node of document.querySelectorAll(`[data-i18n-${attribute}]`)) node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
  }
  // The login button's title only explains why it is disabled until client.js takes over, which removes it.
  const submit = document.getElementById("login-submit");
  if (submit?.hasAttribute("title")) submit.title = t("login.loading");
  for (const choice of document.querySelectorAll("[data-lang]")) {
    choice.setAttribute(choice.getAttribute("role") === "menuitemradio" ? "aria-checked" : "aria-pressed", String(choice.dataset.lang === lang));
  }
}
// The choice is kept per browser; client.js re-renders its dynamic text on the "live-language" event.
function setLanguage(language) {
  if (!languages.includes(language)) return;
  lang = language;
  try { localStorage.setItem("live-lang", language); } catch {}
  translatePage();
  document.dispatchEvent(new Event("live-language"));
}
for (const choice of document.querySelectorAll("[data-lang]")) choice.addEventListener("click", () => setLanguage(choice.dataset.lang));
